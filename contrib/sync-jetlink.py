#!/usr/bin/env python3
"""Import reviewed Jetlink documentation from a recorded repository commit.

Usage: python3 contrib/sync-jetlink.py --source ../jetlink --ref HEAD
Use --check to verify that the existing import matches its recorded commit.
Generated files must not be edited by hand. Local edits stop the next import.
"""
import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path, PurePosixPath
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "docs/jetlink"
MANIFEST = ROOT / "contrib/jetlink-import.json"


def git(source, *args, binary=False):
  return subprocess.check_output(["git", "-C", str(source), *args], text=not binary)


def digest(data):
  return hashlib.sha256(data).hexdigest()


def main():
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument("--source", type=Path, default=ROOT.parent / "jetlink")
  parser.add_argument("--ref", default="HEAD")
  parser.add_argument("--check", action="store_true")
  args = parser.parse_args()
  previous = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else None
  if previous:
    for relative, expected in previous["files"].items():
      path = DEST / relative
      if not path.exists() or digest(path.read_bytes()) != expected:
        raise SystemExit(f"Imported file changed locally: {path}. Save edits before syncing.")
  if args.check and not previous:
    raise SystemExit("No recorded import. Run sync first.")
  commit = git(args.source, "rev-parse", previous["commit"] if args.check else args.ref).strip()
  paths = git(args.source, "ls-tree", "-r", "--name-only", commit, "docs").splitlines()
  generated = {}
  for name in paths:
    relative = str(PurePosixPath(name).relative_to("docs"))
    target = "index.md" if relative == "README.md" else relative
    data = git(args.source, "show", f"{commit}:{name}", binary=True)
    if relative.endswith(".md"):
      body = data.decode()
      # GitHub renders Markdown inside details automatically; Python Markdown
      # requires an explicit opt-in for these same source sections.
      body = body.replace("<details>", '<details markdown="1">')

      def rewrite(match):
        prefix, href, suffix = match.groups()
        if urlsplit(href).scheme or href.startswith(("#", "/", "mailto:")):
          return match.group(0)
        # Root-repo references stay pinned to the reviewed source.
        if href.startswith("../"):
          href = f"https://github.com/zoompilot/jetlink/blob/{commit}/{href[3:]}"
        else:
          href = re.sub(r"^README\.md(?=#|$)", "index.md", href)
        return prefix + href + suffix

      body = re.sub(r'(\]\(|(?:href|src)=")(.*?)(\)|")', rewrite, body)
      # This manual targets the release receiving the current software.
      body = body.replace("zoompilot/develop", "zoompilot/main")
      body = body.replace("`develop`", "`main`").replace("**develop**", "**main**")
      body = body.replace("/tree/develop", "/tree/main").replace("/blob/develop", "/blob/main")
      body = body.replace("Non-Prebuilt Branches", "Prebuilt Branches")
      if relative in {"jetson.md", "macos-app.md", "linux-pc.md", "iphone-app.md", "android-app.md"}:
        # The same setup sentence occurs in each source platform guide.
        body = re.sub(r"Already on zoompilot\? Select\s+.*?Wait for installation, rebooting, and building to finish\.",
                      "Already on zoompilot? Update the `main` release in **Settings > Software**. "
                      "Wait for installation and restarting to finish.", body, flags=re.S)
      if relative == "README.md":
        body = body.replace("# Jetlink guides", """# Jetlink

Run larger driving models on a supported computer or phone connected to
your comma. Jetlink is optional; zoompilot works without it.
{ .zp-lede }

You need a comma 3X or comma 4, a USB 3 data cable, and separate power
for both devices. Choose your platform below for the full requirements.

!!! warning "Experimental"

    If the connection drops or lags while driving, the comma says
    **TAKE CONTROL** and stays engaged on its small model. Be ready to
    take over. Read [daily use](using-jetlink.md) before driving.
""")
      title_match = re.search(r"^# (.+)$", body, re.M)
      title = title_match.group(1) if title_match else relative.removesuffix(".md").replace("-", " ").title()
      header = f'---\ntitle: {json.dumps(title)}\ntype: reference\n---\n\n'
      source_url = f"https://github.com/zoompilot/jetlink/blob/{commit}/{name}"
      body = header + f"<!-- Generated by contrib/sync-jetlink.py from {commit}:{name}. Do not edit. -->\n\n" + body
      body += f"\n\n---\n\n<small>From the [Jetlink documentation]({source_url}).</small>\n"
      data = body.encode()
    generated[target] = data
  files = {name: digest(data) for name, data in sorted(generated.items())}
  record = {"repository": "https://github.com/zoompilot/jetlink", "commit": commit,
            "adaptations": ["README links become index links", "root repository links pinned to source commit",
                            "Markdown enabled inside expandable sections", "driver introduction added to index",
                            "comma install instructions target main prebuilt release"], "files": files}
  if args.check:
    if record != previous:
      raise SystemExit("Recorded import differs from regeneration.")
    print(f"Jetlink import verified: {commit[:12]}, {len(files)} files")
    return
  DEST.mkdir(parents=True, exist_ok=True)
  # Only remove files owned by the previous import, never hand-written pages.
  for name in (previous or {}).get("files", {}):
    if name not in generated:
      (DEST / name).unlink()
  for name, data in generated.items():
    path = DEST / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
  MANIFEST.write_text(json.dumps(record, indent=2) + "\n")
  print(f"Imported {len(files)} files from Jetlink {commit[:12]}")


if __name__ == "__main__":
  main()
